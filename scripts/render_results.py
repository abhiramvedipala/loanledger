#!/usr/bin/env python3
"""Renders RESULTS.md from the raw files in results/. --check fails if RESULTS.md differs."""
import json
import sys
from pathlib import Path


def read_pairs(path):
    return dict(line.split(": ", 1) for line in Path(path).read_text().splitlines())


def render():
    counts = read_pairs("results/count.txt")
    kind = read_pairs("results/kind.txt")
    metrics = json.loads(Path("results/k6-summary.json").read_text())["metrics"]
    latency = metrics["http_req_duration"]
    requests = metrics["http_reqs"]
    failed = metrics["http_req_failed"]["value"] * 100
    rows = [
        ("API endpoints (OpenAPI operations)", counts["endpoints"], "scripts/count.sh"),
        ("Automated tests", counts["tests"], "scripts/count.sh"),
        ("Test failures", counts["failures"], "scripts/count.sh"),
        ("`GET /api/v1/loans` p95 latency", f"{latency['p(95)']:.2f} ms", "scripts/results.sh"),
        ("`GET /api/v1/loans` median latency", f"{latency['med']:.2f} ms", "scripts/results.sh"),
        ("Throughput", f"{requests['rate']:.0f} requests/s", "scripts/results.sh"),
        ("Requests in the 30-second run", f"{requests['count']}", "scripts/results.sh"),
        ("Failed requests", f"{failed:.2f}%", "scripts/results.sh"),
        ("kind deploy: health", kind["health"], "scripts/kind-up.sh"),
        ("kind deploy: ready replicas", kind["ready_replicas"], "scripts/kind-up.sh"),
        ("kind deploy: app pod restarts during rollout", kind["restarts"], "scripts/kind-up.sh"),
        ("kind deploy: seeded loans via the Service", kind["loans"], "scripts/kind-up.sh"),
        ("kind deploy: Kubernetes version", kind["kubernetes"], "scripts/kind-up.sh"),
    ]
    table = "\n".join(f"| {name} | {value} | `{command}` |" for name, value, command in rows)
    return f"""# Results

Generated by `scripts/render_results.py` from the raw files in `results/`. Do not edit by hand.

Re-run everything:

```bash
scripts/kind-up.sh && kind delete cluster --name loanledger
scripts/results.sh
```

| Metric | Value | Source |
|---|---|---|
{table}

Load test: 20 virtual users for 30 seconds with no think time (`scripts/loadtest.js`), one page of 20 loans per
request, against the Compose stack on one laptop. k6, the app and Postgres shared the machine, and Docker ran in a
4-CPU, 8 GB Colima VM that other containers were also using. Treat the latency as a local baseline, not a capacity claim.
"""


def main():
    text = render()
    if "--check" in sys.argv:
        if not Path("RESULTS.md").exists() or Path("RESULTS.md").read_text() != text:
            sys.exit("RESULTS.md does not match results/; run scripts/render_results.py")
        return
    Path("RESULTS.md").write_text(text)


if __name__ == "__main__":
    main()
